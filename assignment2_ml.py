import pandas as pd

df = pd.read_csv("heart.csv")

print("Dataset Shape:", df.shape)

df.head()

df.info()#Dataset Information

#Separate Features and Target
X = df.drop("target", axis=1)

y = df["target"]

print("Features Shape:", X.shape)
print("Target Shape:", y.shape)

#Split Data into Training and Testingfrom sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Shape:", X_train.shape)
print("Testing Shape:", X_test.shape)

#Create test_data.csv
test_df = X_test.copy()

test_df["target"] = y_test

test_df.to_csv(
    "test_data.csv",
    index=False
)

print("test_data.csv created successfully")

#Verify File Createdimport os

print(os.listdir())

#Train All 5 Models.
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC

# Logistic Regression
lr = LogisticRegression(max_iter=1000)
lr.fit(X_train, y_train)

# Decision Tree
dt = DecisionTreeClassifier(random_state=42)
dt.fit(X_train, y_train)

# KNN
knn = KNeighborsClassifier()
knn.fit(X_train, y_train)

# Naive Bayes
nb = GaussianNB()
nb.fit(X_train, y_train)

# SVM
svm = SVC(probability=True)
svm.fit(X_train, y_train)

print("All 5 Models Trained Successfully")

#Calculate All Required Metrics
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    roc_auc_score
)

import pandas as pd

results = []

models = {
    "Logistic Regression": lr,
    "Decision Tree": dt,
    "KNN": knn,
    "Naive Bayes": nb,
    "SVM": svm
}

for name, model in models.items():

    y_pred = model.predict(X_test)

    y_prob = model.predict_proba(X_test)[:, 1]

    results.append([
        name,
        accuracy_score(y_test, y_pred),
        roc_auc_score(y_test, y_prob),
        precision_score(y_test, y_pred),
        recall_score(y_test, y_pred),
        f1_score(y_test, y_pred),
        matthews_corrcoef(y_test, y_pred)
    ])

results_df = pd.DataFrame(
    results,
    columns=[
        "Model",
        "Accuracy",
        "AUC",
        "Precision",
        "Recall",
        "F1",
        "MCC"
    ]
)

results_df

#ave the Comparison Table
results_df.to_csv(
    "model_comparison.csv",
    index=False
)

print("model_comparison.csv saved")

#Find the Best Model
results_df.sort_values(
    by="Accuracy",
    ascending=False
)

